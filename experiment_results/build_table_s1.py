"""build_table_s1.py -- the appendix summary table of the T sweep (paper Table S1).

Writes tables/pullback_T_sweep_ddim_flow_combined.tex (the file paper_appendix.tex inputs): one
table per process (DDIM, flow matching), unweighted mixture, overall accuracy of every classifier
at the largest anchor budget, T = 250 / 500 / 750 as sub-columns, and the learned sampler's
hallucination rate on the test seeds. The budget is fixed rather than picked per cell, so no
number in the table is selected on the test seeds.

    python experiment_results/build_table_s1.py                 # run abc123
    python experiment_results/build_table_s1.py --run myrun
"""
from __future__ import annotations
import argparse
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

PROCESSES = [("ddim", "DDIM", "tab:pullback-T-sweep"),
             ("flow", "flow matching", "tab:pullback-T-sweep-flow")]
MODELS = [("knn", "$k$NN"), ("altered_knn", "w-$k$NN"), ("quadratic", "quadratic"), ("polar3", "polar")]
TS = [250, 500, 750]
VARIANT = "unweighted"


def load(run, proc, T):
    path = os.path.join(ROOT, "output", run, proc, VARIANT, f"T{T}", "results.csv")
    with open(path) as f:
        return {(int(r["n_per_mode"]), r["model"], int(r["K"]), int(r["d"])): r for r in csv.DictReader(f)}


def fmt_int(n):
    return f"{n:,}".replace(",", "{,}")


def table(run, proc, name, label):
    by_T = {T: load(run, proc, T) for T in TS}
    budget = max(k[0] for k in by_T[TS[0]])
    cells = sorted({(k[2], k[3]) for k in by_T[TS[0]] if k[0] == budget})
    n_seeds = max(int(r["n_seeds"]) for r in by_T[TS[0]].values())
    n = len(TS)
    L = ["\\begin{table}[p]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
         f"\\caption{{\\textbf{{Outcome prediction across pullback grids, {name}.}} Overall accuracy "
         f"(\\%, mean over {n_seeds} runs) of each classifier fit on $b = {fmt_int(budget)}$ anchors per "
         f"mode, for $T = {', '.join(map(str, TS))}$ pullback grid points (sub-columns), on the "
         f"unweighted mixture; hall.\\ is the hallucination rate (\\%) of the learned sampler on the "
         f"test seeds, which does not depend on $T$. Best classifier per $(K, d, T)$ in bold; "
         f"$(K, d) = (16, 2)$ is not evaluated (Sec.~\\ref{{app:details_gmm}}).}}",
         f"\\label{{{label}}}",
         "\\begin{tabular}{rrr" + ("c" * n) * len(MODELS) + "}", "\\toprule",
         " & & & " + " & ".join(f"\\multicolumn{{{n}}}{{c}}{{{m}}}" for _, m in MODELS) + " \\\\",
         " ".join(f"\\cmidrule(lr){{{4 + i * n}-{3 + (i + 1) * n}}}" for i in range(len(MODELS))),
         "$K$ & $d$ & hall. & " + " & ".join(str(T) for _ in MODELS for T in TS) + " \\\\", "\\midrule"]
    prev_K = None
    for K, d in cells:
        if prev_K is not None and K != prev_K:
            L.append("\\midrule")
        prev_K = K
        acc = {(m, T): 100 * float(by_T[T][(budget, m, K, d)]["full_acc"]) for m, _ in MODELS for T in TS}
        best = {T: max(round(acc[(m, T)], 1) for m, _ in MODELS) for T in TS}
        hall = 100 * float(by_T[TS[0]][(budget, MODELS[0][0], K, d)]["hall_gt"])
        vals = []
        for m, _ in MODELS:
            for T in TS:
                v = f"{acc[(m, T)]:.1f}"
                vals.append(f"\\textbf{{{v}}}" if round(acc[(m, T)], 1) == best[T] else v)
        L.append(f"{K} & {d} & {hall:.1f} & " + " & ".join(vals) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="abc123")
    args = ap.parse_args()
    out = os.path.join(ROOT, "tables", "pullback_T_sweep_ddim_flow_combined.tex")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    parts = ["% Auto-generated by experiment_results/build_table_s1.py -- needs booktabs"]
    parts += [table(args.run, p, name, label) for p, name, label in PROCESSES]
    with open(out, "w") as f:
        f.write("\n\n".join(parts) + "\n")
    print(f"[table-s1] wrote {out}")


if __name__ == "__main__":
    main()
