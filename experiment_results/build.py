"""build.py -- paper-ready LaTeX tables and heatmaps from a run's results.csv files.

    python experiment_results/build.py                  # run abc123
    python experiment_results/build.py --run myrun --prefix Experiment_results/

Writes, inside this folder:
    tables/<process>_<variant>_a<anchors>.tex         one table per anchor budget, T = 250/500/750
                                                      as sub-columns of each predictor
    figures/<process>_<variant>_T<T>_a<anchors>.pdf   heatmaps: predictor x metric, one per T
and, next to this folder, presenting_results.tex: every table and heatmap. The experimental setup
is not part of it: it is its own document, experimental_setup.tex, also next to this folder.
Paths in presenting_results.tex start with --prefix: the folder's name in the paper project
(Overleaf is case-sensitive, so it must match exactly).
"""
from __future__ import annotations
import argparse
import csv
import glob
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

PROCESSES = [("ddim", "DDIM"), ("flow", "Flow matching"), ("heun", "Heun"), ("rk45", "RK45"),
             ("dpmpp2m", "DPM-Solver++(2M)")]      # a process without results is skipped
VARIANTS = [("unweighted", "Unweighted"), ("weighted", "Weighted")]
TS = [250, 500, 750]
MODELS = [("knn", "$k$NN"), ("altered_knn", "altered $k$NN"), ("quadratic", "quadratic"), ("polar3", "polar")]
METRICS = [("full_acc", "overall accuracy"), ("mode_f1", "mode F1"), ("hall_f1", "hallucination F1")]
MAX_D = 256


def load(run, proc, var, T):
    """{(anchors, model, K, d): row} from results.csv, or None if the sweep is missing."""
    path = os.path.join(ROOT, "output", run, proc, var, f"T{T}", "results.csv")
    if not os.path.exists(path):
        return None
    out = {}
    with open(path) as f:
        for r in csv.DictReader(f):
            out[(int(r["n_per_mode"]), r["model"], int(r["K"]), int(r["d"]))] = r
    return out


def fmt_int(n):
    return f"{n:,}".replace(",", "{,}")


# ---- tables: one per (process, variant, anchor budget), T as sub-columns --------------------
def write_table(by_T, proc, proc_name, var, var_name, a, Ks, ds, n_seeds):
    """by_T: {T: rows}. Bold marks the best predictor at each T within a row."""
    Ts = sorted(by_T)
    tag = f"{proc}_{var}_a{a}"
    n = len(Ts)
    L = ["% Auto-generated by build.py -- needs booktabs",
         "\\begin{table}[t]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}",
         f"\\caption{{\\textbf{{{var_name} {proc_name}, {fmt_int(a)} anchors per mode.}} "
         f"Overall seed-fate accuracy (\\%, mean over {n_seeds} seeds) at "
         f"$T = {', '.join(map(str, Ts))}$ (sub-columns); best predictor per $T$ in bold.}}",
         f"\\label{{tab:{tag}}}",
         "\\begin{tabular}{rr" + ("c" * n) * len(MODELS) + "}", "\\toprule",
         " & & " + " & ".join(f"\\multicolumn{{{n}}}{{c}}{{{m}}}" for _, m in MODELS) + " \\\\",
         " ".join(f"\\cmidrule(lr){{{3 + i * n}-{2 + (i + 1) * n}}}" for i in range(len(MODELS))),
         "$K$ & $d$ & " + " & ".join(" & ".join(map(str, Ts)) for _ in MODELS) + " \\\\", "\\midrule"]
    for i, K in enumerate(Ks):
        if i:
            L.append("\\midrule")
        for d in ds:
            vals = {}                                   # (model, T) -> mean %
            for m, _ in MODELS:
                for T in Ts:
                    r = by_T[T].get((a, m, K, d))
                    if r is not None:
                        vals[(m, T)] = round(100 * float(r["full_acc"]), 1)
            best = {T: max((v for (m, t), v in vals.items() if t == T), default=None) for T in Ts}
            cells = []
            for m, _ in MODELS:
                for T in Ts:
                    v = vals.get((m, T))
                    if v is None:
                        cells.append("--")
                    else:
                        s = f"{v:.1f}"
                        cells.append(f"\\textbf{{{s}}}" if v == best[T] else s)
            L.append(f"{K} & {d} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(os.path.join(HERE, "tables", f"{tag}.tex"), "w") as f:
        f.write("\n".join(L) + "\n")
    return tag


# ---- heatmaps: one per (process, variant, T, anchor budget) --------------------------------
def write_heatmap(rows, proc, proc_name, var, var_name, T, a, Ks, ds, n_seeds, prefix):
    tag = f"{proc}_{var}_T{T}_a{a}"
    fig, axes = plt.subplots(len(MODELS), len(METRICS), figsize=(3.6 * len(METRICS), 1.9 * len(MODELS)),
                             squeeze=False, sharex=True, sharey=True)
    for i, (m, m_name) in enumerate(MODELS):
        for j, (key, label) in enumerate(METRICS):
            ax = axes[i, j]
            M = np.full((len(Ks), len(ds)), np.nan)
            for ki, K in enumerate(Ks):
                for di, d in enumerate(ds):
                    r = rows.get((a, m, K, d))
                    if r is not None:
                        M[ki, di] = 100 * float(r[key])
            im = ax.imshow(M, vmin=0, vmax=100, aspect="auto", cmap="viridis")
            for ki in range(len(Ks)):
                for di in range(len(ds)):
                    v = M[ki, di]
                    if v == v:
                        ax.text(di, ki, f"{v:.0f}", ha="center", va="center", fontsize=7,
                                color="white" if v < 60 else "black")
            ax.set_xticks(range(len(ds)), [str(d) for d in ds], fontsize=7)
            ax.set_yticks(range(len(Ks)), [str(K) for K in Ks], fontsize=7)
            if i == 0:
                ax.set_title(label, fontsize=10)
            if i == len(MODELS) - 1:
                ax.set_xlabel("dimension $d$", fontsize=8)
            if j == 0:
                ax.set_ylabel(f"{m_name}\nmodes $K$", fontsize=9)
    cb = fig.colorbar(im, ax=axes.ravel().tolist(), fraction=0.02, pad=0.02)
    cb.set_label("%", fontsize=8); cb.ax.tick_params(labelsize=7)
    fig.savefig(os.path.join(HERE, "figures", f"{tag}.pdf"), bbox_inches="tight")
    plt.close(fig)
    return "\n".join([
        "\\begin{figure}[t]", "\\centering",
        f"\\includegraphics[width=\\linewidth]{{{prefix}figures/{tag}.pdf}}",
        f"\\caption{{\\textbf{{{var_name} {proc_name}, $T={T}$, {fmt_int(a)} anchors per mode.}} "
        f"Overall accuracy, mode F1 and hallucination F1 (\\%, mean over {n_seeds} seeds) per predictor "
        f"(rows) on the $(K, d)$ grid; empty cells were not run.}}",
        f"\\label{{fig:{tag}}}", "\\end{figure}"])


DOC_HEAD = r"""% presenting_results.tex -- every table and heatmap in {prefix}. Auto-generated by
% {folder}/build.py. Sits in the project root, next to the {prefix} folder.
% Compile it: Menu -> Main document -> presenting_results.tex.
\documentclass[11pt]{{article}}
\usepackage[margin=1in]{{geometry}}
\usepackage[T1]{{fontenc}}
\usepackage{{times}}
\usepackage{{amsmath}}
\usepackage{{amssymb}}
\usepackage{{booktabs}}
\usepackage{{graphicx}}
\usepackage[hidelinks]{{hyperref}}
\setcounter{{topnumber}}{{3}}
\setcounter{{totalnumber}}{{4}}
\renewcommand{{\topfraction}}{{0.95}}
\renewcommand{{\textfraction}}{{0.05}}
\renewcommand{{\floatpagefraction}}{{0.8}}

\title{{Seed-fate prediction: full results}}
\date{{}}
\begin{{document}}
\maketitle
\tableofcontents
\clearpage
"""

RESULTS_INTRO = r"""
\section{{Tables: overall accuracy}}
\noindent The experimental setup, and how these tables and heatmaps are generated, are described in
the separate document \texttt{{experimental\_setup.tex}}.

\noindent Each table reports overall seed-fate accuracy (\%, mean over {n_seeds} seeds) on the
$(K, d)$ grid, $d \le {max_d}$, for one anchor budget, with $T = {Ts}$ as sub-columns of each
predictor; the best predictor at each $T$ is in bold. Heatmaps show overall accuracy, mode F1 and
hallucination F1 for each predictor, one per $T$ and anchor budget. $K=16$, $d=2$ was not run (--).
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="abc123")
    ap.add_argument("--prefix", default="Experiment_results/",
                    help="this folder's path in the paper project, as used in presenting_results.tex")
    args = ap.parse_args()
    for sub in ("tables", "figures"):
        os.makedirs(os.path.join(HERE, sub), exist_ok=True)
        for old in glob.glob(os.path.join(HERE, sub, "*")):  # drop outputs of earlier layouts
            os.remove(old)

    tables, figures, n_seeds = [], [], 0
    for proc, proc_name in PROCESSES:
        for var, var_name in VARIANTS:
            by_T = {T: r for T in TS if (r := load(args.run, proc, var, T)) is not None}
            if not by_T:
                print(f"[tex] missing {proc}/{var}, skipped")
                continue
            allrows = [k for rows in by_T.values() for k in rows]
            Ks = sorted({k[2] for k in allrows})
            ds = sorted({k[3] for k in allrows if k[3] <= MAX_D})
            anchors = sorted({k[0] for k in allrows})
            ns = max(int(r["n_seeds"]) for rows in by_T.values() for r in rows.values())
            n_seeds = max(n_seeds, ns)

            tables.append(f"\\subsection{{{var_name} {proc_name}}}")
            for a in anchors:
                tag = write_table(by_T, proc, proc_name, var, var_name, a, Ks, ds, ns)
                tables.append(f"\\input{{{args.prefix}tables/{tag}}}")
            tables.append("\\clearpage")
            for T, rows in by_T.items():
                figures.append(f"\\subsection{{{var_name} {proc_name}, $T={T}$}}")
                figures += [write_heatmap(rows, proc, proc_name, var, var_name, T, a, Ks, ds, ns, args.prefix)
                            for a in anchors]
                figures.append("\\clearpage")
            print(f"[tex] {proc}/{var}: {len(anchors)} tables, {len(anchors) * len(by_T)} heatmaps")

    fill = dict(n_seeds=n_seeds, max_d=MAX_D, Ts=", ".join(map(str, TS)))
    doc = (DOC_HEAD.format(prefix=args.prefix, folder=os.path.basename(HERE), **fill)
           + RESULTS_INTRO.format(**fill) + "\n".join(tables)
           + "\n\n\\section{Heatmaps}\n" + "\n".join(figures) + "\n\\end{document}\n")
    with open(os.path.join(ROOT, "presenting_results.tex"), "w") as f:
        f.write(doc)
    print(f"[tex] wrote {os.path.join(ROOT, 'presenting_results.tex')}")


if __name__ == "__main__":
    main()
